/* ── Internal helpers ────────────────────────────────────────────────── */

static inline uint16_t rgb565(uint8_t r, uint8_t g, uint8_t b)
{
    return (uint16_t)(((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3));
}

/** Fill the whole PSRAM framebuffer with @p color. */
static void fb_fill(uint16_t color)
{
    for (size_t i = 0; i < FB_SIZE; i++) {
        fb[i] = color;
    }
}

/** Put one pixel at (x, y). Out-of-bounds silently ignored. */
static void fb_put(int x, int y, uint16_t color)
{
    if (x < 0 || x >= BOARD_LCD_H_RES || y < 0 || y >= BOARD_LCD_V_RES) return;
    fb[y * BOARD_LCD_H_RES + x] = color;
}

/** Push the framebuffer to the display. */
static void fb_flush(void)
{
    esp_lcd_panel_draw_bitmap(panel_handle, 0, 0,
                              BOARD_LCD_H_RES, BOARD_LCD_V_RES, fb);
}

